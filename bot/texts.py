def is_weekend(day: date) -> bool:
    """Правда, если день — пятница, суббота или воскресенье (ПТ–ВС)."""
    return day.weekday() in WEEKEND_DAYS


def get_tariff(tariff_key: str | None) -> Tariff | None:
    """Тариф по ключу из ``callback_data``."""
    return TARIFF_BY_KEY.get(tariff_key) if tariff_key else None


def prepayment_required(time_key: str | None, day: date) -> bool:
    """Нужна ли полная предоплата.

    По правилам клуба предоплата берётся только на **ночные пакеты** и только в
    **выходные (ПТ–ВС)**; в остальные дни и на остальных пакетах гость может
    оплатить на месте.
    """
    return time_key == TIME_NIGHT_KEY and is_weekend(day)


def amount_due(tariff_key: str | None, time_key: str | None, day: date) -> int | None:
    """Сумма к оплате, если она известна заранее (пакет с фиксированной ценой).

    Для почасовой игры («Сейчас») и своего времени сумма зависит от длительности,
    поэтому возвращаем ``None``.
    """
    tariff = get_tariff(tariff_key)
    if tariff is None:
        return None
    if time_key == TIME_MORNING_KEY:
        return tariff.morning
    if time_key == TIME_DAY_KEY:
        return tariff.day
    if time_key == TIME_NIGHT_KEY:
        return tariff.night_price(day)
    return None


def tariff_button_label(tariff: Tariff) -> str:
    """Подпись кнопки тарифа с главной ценой (укладывается в 64 символа)."""
    return f"{tariff.emoji} {tariff.title} — от {tariff.hour1} ₽/час"


def tariff_price_hint(tariff_key: str | None, time_key: str | None, day: date) -> str:
    """Подсказка о цене для выбранной пары «тариф + время»."""
    tariff = get_tariff(tariff_key)
    if tariff is None:
        return PRICE_HINT_LOOK_AT_PRICE_LIST

    if time_key == TIME_MORNING_KEY:
        return f"утро ({MORNING_SLOT}) — {tariff.morning} ₽"
    if time_key == TIME_DAY_KEY:
        return f"день ({DAY_SLOT}) — {tariff.day} ₽"
    if time_key == TIME_NIGHT_KEY:
        note = "выходные (ПТ–ВС)" if is_weekend(day) else "будни"
        return f"ночной пакет ({NIGHT_SLOT}) — {tariff.night_price(day)} ₽, {note}"
    return f"{tariff.hour1} ₽/час • 3 часа {tariff.hour3} ₽ • 5 часов {tariff.hour5} ₽"


def package_key_from_slot(time_slot: str) -> str | None:
    """Определить пакет по строке времени из базы: «Ночь (22:00–08:00)» → ``night``.

    Нужно там, где известна только сохранённая строка (например, администратор
    смотрит заявку): по ней можно снова найти цену пакета.
    """
    for prefix, key in (
        ("Ночь (", TIME_NIGHT_KEY),
        ("Утро (", TIME_MORNING_KEY),
        ("День (", TIME_DAY_KEY),
    ):
        if time_slot.startswith(prefix):
            return key
    return None


def amount_for_booking(tariff_title: str, time_slot: str, day: date) -> int | None:
    """Сумма к оплате по сохранённым названию тарифа и строке времени.

    Возвращает ``None``, если сумму заранее не узнать (почасовая игра или своё
    время гостя).
    """
    tariff = next((t for t in TARIFFS if t.title == tariff_title), None)
    if tariff is None:
        return None
    return amount_due(tariff.key, package_key_from_slot(time_slot), day)


def amount_text(tariff_key: str | None, time_key: str | None, day: date) -> str:
    """Строка «К оплате» для шага оплаты: точная сумма пакета или «по прайсу»."""
    amount = amount_due(tariff_key, time_key, day)
    if amount is None:
        return f"по прайсу: {tariff_price_hint(tariff_key, time_key, day)}"
    return f"<b>{amount} ₽</b>"


def build_price_list(club: ClubInfo) -> str:
    """Полный прайс-лист клуба — в том виде, в каком его публикует сам клуб."""
    blocks: list[str] = []
    for tariff in TARIFFS:
        blocks.append(
            f"<b>{tariff.header()}</b>\n"
            f"1 час: {tariff.hour1} ₽ • 3 часа: {tariff.hour3} ₽ • 5 часов: {tariff.hour5} ₽\n"
            f"Утро ({MORNING_SLOT}): {tariff.morning} ₽ • День ({DAY_SLOT}): {tariff.day} ₽\n"
            f"Ночь ({NIGHT_SLOT}): {tariff.night} ₽ • Ночь ПТ–ВС: {tariff.night_weekend} ₽"
        )

    return render(
        _PRICE_LIST_TEMPLATE,
        club,
        tariffs="\n\n".join(blocks),
        night_slot=NIGHT_SLOT,
        morning_slot=MORNING_SLOT,
        day_slot=DAY_SLOT,
    )


