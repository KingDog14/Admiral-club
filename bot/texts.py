#: Ночной пакет — с 22:00 до 08:00 (оплачивается целиком).
NIGHT_SLOT: str = "22:00–08:00"
#: Утренний пакет.
MORNING_SLOT: str = "8:00–13:00"
#: Дневной пакет.
