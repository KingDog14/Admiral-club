@dataclass(frozen=True, slots=True)
class Tariff:
    """Один тариф клуба: зал, количество ПК и цены всех пакетов (в рублях)."""

    key: str
    title: str
    emoji: str
    pcs: int | None
    hour1: int
    hour3: int
    hour5: int
    morning: int
    day: int
    night: int
    night_weekend: int
    description: str

    def night_price(self, day: date) -> int:
        """Цена ночного пакета: в ПТ–ВС действует повышенный тариф."""
        return self.night_weekend if is_weekend(day) else self.night

    def header(self) -> str:
        """Шапка тарифа в прайсе: «🟢 STANDART (16 PC)»."""
        suffix = f" ({self.pcs} PC)" if self.pcs else ""
        return f"{self.emoji} {self.title.upper()}{suffix}"


